# ============================================================
# 4. yield from 语法
# ============================================================

def chain(*iterables):
    """连接多个可迭代对象"""
    for iterable in iterables:
        yield from iterable


# ============================================================
# 5. 实用示例：读取大文件
# ============================================================

def read_large_file(file_path):
    """逐行读取大文件，避免一次性加载到内存"""
    with open(file_path, 'r') as f:
        for line in f:
            yield line.strip()


